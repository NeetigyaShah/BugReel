import type {
  BugReelReport,
  DiagnosticFinding,
  InputEvent,
  NetworkEvent,
  RawBugReelEvent,
  ReportMeta,
  ReporterAnswers,
  StoryStep,
} from '../types';
import { buildStory, eventToStep, inline, isFailedRequest } from './story';

/**
 * Report compilers — deterministic string generation from scrubbed,
 * post-Firewall events. Every output is a pure function of the compiled
 * report inputs: same events in, byte-identical output out.
 */

const SEVERITY_MARK: Record<string, string> = { critical: '🚨', warning: '⚠️' };

/** The requests worth reproducing — the same failure predicate the story uses. */
const failedRequests = (events: RawBugReelEvent[]): NetworkEvent[] =>
  events.filter((e): e is NetworkEvent => (e.type === 'fetch' || e.type === 'xhr') && isFailedRequest(e));

const shellQuote = (value: string): string => `'${value.replace(/'/g, `'\\''`)}'`;

/** A method is token-safe only when it is a bare word; anything else gets quoted. */
const methodArg = (method: string): string => (/^[A-Za-z]+$/.test(method) ? method : shellQuote(method));

/** Resolve a request URL against the page origin so the cURL is runnable. */
const absoluteUrl = (raw: string, meta: ReportMeta): string => {
  try {
    return new URL(raw, meta.url).href;
  } catch {
    return raw;
  }
};

/** cURL commands for every failed request, in event order. */
export function compileCurl(events: NetworkEvent[], meta: ReportMeta): string | undefined {
  const failed = failedRequests(events);
  if (!failed.length) return undefined;
  const commands = failed.map((event) => {
    const parts = [
      `curl --request ${methodArg(event.method)} --url ${shellQuote(absoluteUrl(inline(event.url), meta))}`,
    ];
    for (const [name, value] of Object.entries(event.requestHeaders ?? {})) {
      parts.push(`--header ${shellQuote(`${inline(name)}: ${value}`)}`);
    }
    if (event.requestBody) parts.push(`--data-raw ${shellQuote(event.requestBody)}`);
    const note =
      event.status === undefined || event.status === 0 || event.corsBlocked
        ? `# note: ${inline(event.method)} ${inline(event.url)} — connection failed at the browser level (CORS or network), so cURL may succeed where the page could not\n`
        : '';
    return note + parts.join(' ');
  });
  return commands.join('\n\n');
}

const isSensitiveValue = (value: string): boolean => value === '[REDACTED]' || /^\[\d+ chars\]$/.test(value);

/** A Playwright spec that replays the user's own clicks and inputs. */
export function compilePlaywright(
  events: RawBugReelEvent[],
  meta: ReportMeta,
): string {
  const lines = [
    `import { test } from '@playwright/test';`,
    ``,
    `// Generated by BugReel from a captured session — deterministic replay.`,
    `test('bugreel replay', async ({ page }) => {`,
    `  await page.goto(${JSON.stringify(meta.url)});`,
  ];
  for (const event of events) {
    const note = eventToStep(event)?.text;
    switch (event.type) {
      case 'click':
        lines.push(`  await page.click(${JSON.stringify(event.target.selector)}); // ${note}`);
        break;
      case 'input': {
        const input = event as InputEvent;
        const selector = JSON.stringify(input.target.selector);
        if (isSensitiveValue(input.value)) {
          lines.push(`  // Skipped sensitive field: ${inline(input.target.selector)} (value withheld)`);
        } else if (input.target.tagName === 'select') {
          lines.push(`  await page.selectOption(${selector}, ${JSON.stringify(input.value)}); // ${note}`);
        } else if (input.target.inputType === 'checkbox' || input.target.inputType === 'radio') {
          const checked = ['true', 'on', '1', 'checked'].includes(input.value) ? 'check' : 'uncheck';
          lines.push(`  await page.${checked}(${selector}); // ${note}`);
        } else {
          lines.push(`  await page.fill(${selector}, ${JSON.stringify(input.value)}); // ${note}`);
        }
        break;
      }
      case 'route':
        lines.push(`  // ${note}`);
        break;
      case 'fetch':
      case 'xhr':
        if (isFailedRequest(event)) lines.push(`  // ${note}`);
        break;
      default:
        break;
    }
  }
  lines.push(`});`);
  return lines.join('\n');
}

export interface PromptInput {
  events: RawBugReelEvent[];
  findings: DiagnosticFinding[];
  meta: ReportMeta;
  answers?: ReporterAnswers;
}

/** The Cursor/AI fix prompt — observed evidence plus where to look, no diagnosis. */
export function compilePrompt({ events, findings, meta, answers }: PromptInput): string {
  const app = meta.project ?? meta.app ?? 'this application';
  const lines: string[] = [
    `Fix this bug in ${app}. A reporter captured it in the browser; the evidence below was recorded automatically — detector findings are pattern verdicts, everything else is observed fact.`,
    ``,
    `## Reporter's account`,
    answers?.tryingToDo
      ? `- They were trying to: ${inline(answers.tryingToDo)}`
      : `- (the reporter left "what were you trying to do" empty)`,
    answers?.wentWrong
      ? `- What went wrong for them: ${inline(answers.wentWrong)}`
      : `- (the reporter left "what went wrong" empty)`,
    ``,
    `## What happened`,
  ];
  if (findings.length) {
    for (const f of findings) {
      lines.push(`- **${inline(f.headline)}** ${inline(f.explanation)}${f.selector ? ` (element: \`${inline(f.selector)}\`)` : ''}`);
    }
  } else {
    lines.push(`- No detectors fired — reconstruct the failure from the story below.`);
  }
  lines.push(``, `## What the reporter did`);
  for (const step of buildStory(events, findings)) {
    if (step.kind !== 'finding') lines.push(`- ${step.text}`);
  }
  const failed = failedRequests(events);
  if (failed.length) {
    lines.push(``, `## The failing request${failed.length > 1 ? 's' : ''}`);
    for (const f of failed) {
      lines.push(`- ${inline(f.method)} ${inline(f.url)}${f.status === undefined || f.status === 0 ? ' never got a response (CORS or network failure)' : ` failed with ${f.status}`}`);
      if (f.requestBody) lines.push(`  - request body:`, `    ~~~`, `    ${f.requestBody}`, `    ~~~`);
      if (f.responseBody) lines.push(`  - response body:`, `    ~~~`, `    ${f.responseBody}`, `    ~~~`);
    }
  }
  lines.push(``, `## Where to look`);
  const selector = findings.find((f) => f.selector)?.selector;
  if (selector) lines.push(`- The handler for clicks on \`${inline(selector)}\``);
  if (failed.length) {
    lines.push(`- The request code for \`${failed.map((f) => `${inline(f.method)} ${inline(f.url)}`).join('`, `')}\` and whatever renders errors for it`);
  }
  if (!selector && !failed.length) {
    lines.push(`- Re-run the story steps above until the failure reproduces, then instrument that path`);
  }
  lines.push(``, `Page: ${meta.url}`);
  return lines.join('\n');
}

const relTime = (at: number, capturedAt: number): string =>
  `T-${(Math.max(0, capturedAt - at) / 1000).toFixed(1)}s`;

const storyLine = (step: StoryStep, capturedAt: number): string => {
  const mark = step.kind === 'finding' ? `${SEVERITY_MARK[step.severity ?? 'warning'] ?? '⚠️'} ` : '';
  return `- ${mark}\`${relTime(step.at, capturedAt)}\` ${step.text}`;
};

/** report.md — the frozen four-part artifact (GLOSSARY: Report). */
export function compileMarkdown(report: BugReelReport): string {
  const { meta, reporterAnswers: answers, findings, storySteps, outputs } = report;
  const capturedAtText = Number.isFinite(meta.capturedAt)
    ? new Date(meta.capturedAt).toISOString()
    : 'unknown time';
  const lines: string[] = [
    `# BugReel Bug Report`,
    ``,
    `> Captured on \`${meta.url}\` at ${capturedAtText} · SDK ${meta.sdkVersion} · session ${meta.sessionId}${meta.project ? ` · ${meta.project}` : ''}${meta.app ? `${meta.project ? '/' : ' · '}${meta.app}` : ''}`,
    ``,
    `## 1. What the reporter said`,
    ``,
    `- **Trying to:** ${answers.tryingToDo ? inline(answers.tryingToDo) : '(not answered)'}`,
    `- **Went wrong:** ${answers.wentWrong ? inline(answers.wentWrong) : '(not answered)'}`,
    ...(report.media?.length ? [`- **Media:** ${report.media.map(inline).join(', ')}`] : []),
    ``,
    `## 2. What Happened`,
    ``,
  ];
  if (findings.length) {
    for (const f of findings) {
      lines.push(`- ${SEVERITY_MARK[f.severity] ?? '⚠️'} **${inline(f.headline)}.** ${inline(f.explanation)}`);
    }
  } else {
    lines.push(`No detectors fired — the event story below is the best account of what happened.`);
  }
  lines.push(``, `## 3. Story`, ``, `*The ~60 seconds leading to the report, in the reporter's own steps:*`, ``);
  for (const step of storySteps) lines.push(storyLine(step, meta.capturedAt));

  lines.push(``, `## 4. Developer toolkit`, ``);
  const blocks: Array<[string, string, string | undefined]> = [
    ['**AI fix prompt** (paste into Cursor / Claude / Copilot)', 'md', outputs.cursorPrompt],
    ['**cURL** — replay the failed request', 'bash', outputs.curl],
    ['**Playwright repro** — rerun the user\'s clicks', 'ts', outputs.playwright],
  ];
  for (const [summary, lang, content] of blocks) {
    if (!content) continue;
    // Four-tilde fences so a captured `~~~` inside a body can't close them.
    lines.push(
      `<details><summary>${summary}</summary>`,
      ``,
      `~~~~${lang}`,
      content,
      `~~~~`,
      ``,
      `</details>`,
      ``,
    );
  }
  return lines.join('\n') + '\n';
}
